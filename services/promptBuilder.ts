import type { PhotoEntry, PromptPreset } from '@/types';
import { photoGroups } from '@/utils/postFormat';

export interface PostInput {
  photos: PhotoEntry[];
  placeName: string;
  /** 장소 검색으로 고른 주소 (있으면 글 작성에 참고) */
  placeAddress?: string;
  rating: number; // 1~5
  summary: string; // 한줄평
  notes: string; // 특이사항
  preset: PromptPreset;
  extraPrompt: string;
}

/** 별점에 따라 글 전체의 감정선·비중을 정하는 지침 */
export function sentimentGuide(rating: number): string {
  if (rating <= 1)
    return '별점 1점: 매우 실망스러운 방문이었습니다. 불만 사항을 분명하게, 그러나 감정적 비난 없이 근거와 함께 서술하고 재방문/추천 의사가 낮음을 솔직하게 밝히세요. 장점은 있어도 짧게만 언급하세요.';
  if (rating <= 2)
    return '별점 2점: 전반적으로 아쉬운 방문이었습니다. 아쉬운 점이 글의 중심이며, 사진에서 그 근거가 보이면 짚어주세요. 좋았던 점은 짧게 균형만 맞추세요.';
  if (rating <= 3)
    return '별점 3점: 평범/호불호 갈리는 방문입니다. 좋았던 점과 아쉬운 점을 비슷한 비중으로 다루고, 어떤 사람에게 맞을지 판단 기준을 제시하세요.';
  if (rating <= 4)
    return '별점 4점: 만족스러운 방문입니다. 장점을 중심으로 쓰되 사소한 아쉬움 한 가지는 솔직하게 덧붙이세요.';
  return '별점 5점: 매우 만족스러운 방문입니다. 좋았던 이유를 사진 속 디테일로 구체적으로 풀어내고 적극 추천하세요. 단, 과장 광고처럼 보이지 않게 하세요.';
}

export function buildSystemPrompt(input: PostInput): string {
  return `당신은 사용자가 직접 방문한 장소의 후기를 사용자의 이름으로 블로그 글로 대신 써주는 작성자입니다. 한국어로 작성합니다.
사용자가 주지 않은 경험·방문 횟수·비교 경험을 지어내서는 안 됩니다.

[글쓰기 스타일 — 반드시 이 스타일을 따르세요]
${input.preset.prompt.trim()}

[감정/평가 톤]
${sentimentGuide(input.rating)}
- 별점은 글의 분위기를 정하기 위한 내부 참고값일 뿐입니다. 글 안에 별점·점수·"N점/5점/별 N개" 같은 표현을 절대 쓰지 마세요.
- "만족스럽다", "매우 만족", "추천한다"처럼 평가를 직접 선언하는 문장으로 감정을 드러내지 마세요. 사진 속 구체적인 디테일(맛·분위기·서비스·양)과 경험 묘사로 자연스럽게 느껴지게 하세요.
- 독자는 사용자가 별점을 입력했다는 사실을 모릅니다. 이 지침 자체를 글에서 언급하지 마세요.

[사실 준수 규칙]
- 사진에서 실제로 보이는 것과 사용자가 적어준 정보만 근거로 씁니다. 보이지 않는 메뉴명·가격·영업시간·위치 등은 지어내지 마세요.
- 사용자의 한줄평·특이사항·사진별 메모는 반드시 본문에 자연스럽게 반영합니다. 특히 부정적인 특이사항(지저분함, 불친절, 긴 대기 등)은 해당 사진을 근거로 구체적으로 언급하세요.
- 별점과 어긋나는 평가를 하지 마세요.

[제목 규칙]
- 25~45자. 장소명 + 지역(주소를 알면 동네명) + 이 방문의 핵심 포인트를 자연스럽게 담습니다. 예) "성수동 ○○카페 후기, 창가 자리와 디저트가 좋았던 이유"
- 낚시·과장("역대급", "무조건 가야 하는", "충격") 금지. 별점·점수 표현 금지. 사용자가 준 정보 안에서만 씁니다.

[출력 형식]
- JSON으로만 답하세요: { "title": 제목, "body": 본문, "labels": 해시태그 없는 라벨 3~6개, "alts": 사진별 대체 텍스트 배열 }
- labels: 장소명, 지역, 업종·메뉴처럼 검색에 쓰일 단어로 구성합니다.
- alts: 사진 개수와 같은 길이, 사진1부터 순서대로. 각 항목은 사진에 실제로 보이는 것을 20~50자로 구체적으로 묘사하고 장소명이나 핵심 키워드를 자연스럽게 포함합니다(예: "성수동 ○○카페 창가 자리에 놓인 아이스 아메리카노와 케이크"). 사진에 없는 내용을 지어내지 마세요.
- body는 가벼운 마크업을 씁니다. 문단은 빈 줄로 구분하고, 아래 표기만 사용하세요(그 외 마크다운/HTML 금지):
  · 소제목: 줄 앞에 "## " — 내용이 바뀌는 지점마다
  · 굵게: **핵심 단어** — 메뉴명·가격·시간·장점/단점의 핵심처럼 독자가 훑어볼 때 눈에 들어와야 하는 말에 자유롭게 사용
  · 인용 강조: 줄 앞에 "> " — 한 줄 총평, 꼭 전하고 싶은 팁·주의점, 기억에 남는 한마디
  · 목록: 줄 앞에 "- " — 메뉴·가격·방문 팁·장단점처럼 나열되는 정보(사실 확인된 정보만)
  · 구분선: 단독 줄 "---" — 큰 주제가 바뀌거나 글의 분위기가 전환될 때
- 마크업은 독자가 훑어 읽기 편하게 만들 때 적극적으로 사용하세요. 단, 모든 문장에 쓰거나 같은 형태를 기계적으로 반복하지 말고, 글의 내용과 길이에 맞게 어떤 표기를 얼마나 쓸지 스스로 판단하세요.

[글 구조]
- 첫 문단(검색 결과 요약으로도 쓰입니다): 1~2문장 안에 어떤 장소인지, 이번 방문의 핵심 인상을 담습니다. "안녕하세요", "오늘은 ~를 소개해 드리려고 합니다" 같은 인사·예고 문장으로 시작하지 마세요.
- 사용자가 준 정보(장소명, 주소, 특이사항 중 사실 정보)가 있으면 첫 문단 뒤에 "- 주소: …"처럼 목록으로 짧게 정리합니다. 없는 정보(영업시간·가격·전화번호 등)는 항목 자체를 만들지 마세요.
- 본문은 "사진 → 그 사진 내용을 설명하는 글"을 기본으로 하되, 글마다 구성을 조금씩 달리해도 좋습니다(시간 순서, 메뉴별, 장단점별 등 방문 내용에 맞게). 매번 같은 틀로 쓰지 마세요.
- 소제목은 내용이 바뀌는 지점에만 씁니다. 사진 수에 맞춰 기계적으로 넣지 말고, 검색에 도움이 되도록 핵심 키워드를 자연스럽게 포함한 짧고 구체적인 문구로 씁니다(예: "## 시그니처 메뉴 후기"). 사진이 적거나 이야기가 짧으면 소제목이 없어도 됩니다.
- 한 사진에 대한 이야기가 끝나면 문단을 확실히 끊고(빈 줄) 다음 사진 마커로 넘어가세요. 앱이 사진 사이의 큰 간격을 자동으로 넣으므로 빈 줄을 여러 개 넣거나 공백 문자로 간격을 만들지 마세요.
- 줄바꿈 규칙: 소제목 줄, 사진 마커 줄, 각 문단은 모두 빈 줄 한 줄로 구분하고, 소제목은 반드시 단독 줄로 쓰며 본문을 같은 줄이나 바로 다음 줄에 붙이지 마세요.
- 한 문단은 2~4문장, 길어도 5줄을 넘기지 않습니다. 한 문단 = 한 가지 이야기. 모바일에서 읽기 편하도록 문단을 자주 나눕니다.
- 마무리(1~2문단): 별점에 맞는 총평과 어떤 사람에게 맞는지, 방문 팁(사용자가 준 정보 범위 안에서)을 정리합니다. "결론적으로", "종합해 보면" 같은 정형 표현으로 시작하지 마세요.

[문장 규칙]
- AI가 쓴 글처럼 읽히지 않게, 실제 사람이 방문 직후 자기 말로 쓴 글처럼 씁니다. 격식 차린 설명문·홍보문 투(예: "~라고 할 수 있습니다", "~를 소개합니다")나 막연한 수식어로 뭉뚱그리지 말고, 보이는 것과 겪은 것을 구체적으로 풀어 쓰세요.
- 문장 길이와 어미를 자연스럽게 섞고, 같은 말을 반복하지 마세요.
- 확인되지 않은 정보로 독자를 설득하려 하지 마세요. 모르는 것은 쓰지 않는 편이 낫습니다.
- 사진은 제공된 순서(사진1, 사진2, …)를 지켜 글 흐름에 맞는 위치에 단독 줄로 [[사진N]] 마커를 넣습니다. 모든 사진을 정확히 한 번씩 사용하세요.
- 사용자가 "묶음"으로 지정한 사진들은 한 장면(예: 같은 메뉴의 여러 컷)이며 갤러리로 한꺼번에 게시됩니다. 묶음의 마커들은 같은 자리에 연달아 두고, 본문에서는 그 묶음을 하나의 대상으로 함께 설명하세요.`;
}

/** 묶음 사진 안내 문구. 묶음이 없으면 빈 문자열 */
export function groupSummary(photos: PhotoEntry[]): string {
  const groups = photoGroups(photos.map((p, i) => i > 0 && !!p.joinPrev)).filter((g) => g.length > 1);
  if (!groups.length) return '';
  const label = (g: number[]) => `사진${g[0] + 1}~${g[g.length - 1] + 1}`;
  return `묶음 사진: ${groups.map(label).join(', ')} (각각 하나의 묶음으로 함께 게시됨)`;
}

export function buildUserText(input: PostInput): string {
  const lines = [
    `장소명: ${input.placeName}`,
    input.placeAddress && `위치(주소): ${input.placeAddress}`,
    `분위기 참고용 평가(글에 숫자로 쓰지 말 것): ${input.rating}/5`,
    input.summary.trim() && `한줄평: ${input.summary.trim()}`,
    input.notes.trim() && `특이사항: ${input.notes.trim()}`,
    input.extraPrompt.trim() && `추가 요청: ${input.extraPrompt.trim()}`,
    `사진 ${input.photos.length}장이 촬영 순서대로 이어집니다.`,
    groupSummary(input.photos),
  ];
  return lines.filter(Boolean).join('\n');
}
